import type { PropDoc, PropsDoc } from "../types.ts";
import type {
  CatalogueEntry,
  CatalogueGroup,
  PrimitiveEntry,
} from "./catalogue.ts";

export interface AgentIndexInput {
  /** The generated props documents, keyed by export name. */
  docs: ReadonlyMap<string, PropsDoc>;
  catalogue: readonly CatalogueGroup[];
  /** Example source per component name. */
  examples: ReadonlyMap<string, string>;
  /** The members of each primitive, keyed by `PrimitiveEntry.name`. */
  primitiveMembers: ReadonlyMap<string, readonly string[]>;
}

export interface AgentIndex {
  /** Markdown per path, relative to the references directory. */
  files: Map<string, string>;
  /** Documented components that no catalogue group lists. */
  unlisted: string[];
  /** Catalogue names that have no document. */
  unknown: string[];
  /** Example names that match no listed component. */
  unusedExamples: string[];
}

const OTHER_SLUG = "other";

const GENERATED_NOTICE =
  "<!-- Generated by packages/props-codegen from the props of @tuja/ui and src/agent-index/{catalogue.ts,examples.tsx}. Do not edit: change those files or the JSDoc, then run `pnpm --filter web codegen:agent-index`. -->";

const MIN_SUMMARY_WORDS = 4;

const ABBREVIATION = /\b(?:e\.g|i\.e|etc|vs|cf)\.$/i;

/**
 * The first sentence of the first paragraph, never cut inside a code span.
 * A sentence of a few words, such as "Visual look.", says too little alone,
 * so the next sentence joins it.
 */
export function summaryOf(text: string): string {
  const paragraph = text.split("\n\n")[0] ?? "";
  let inCode = false;
  for (let index = 0; index < paragraph.length; index++) {
    const character = paragraph.charAt(index);
    if (character === "`") {
      inCode = !inCode;
      continue;
    }
    if (inCode || !".!?".includes(character)) continue;
    const next = paragraph.charAt(index + 1);
    if (next !== "" && !/\s/.test(next)) continue;
    const head = paragraph.slice(0, index + 1);
    if (ABBREVIATION.test(head)) continue;
    if (head.split(/\s+/).length >= MIN_SUMMARY_WORDS) return head;
  }
  return paragraph;
}

function code(text: string): string {
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}

function importPathOf(doc: PropsDoc): string {
  return doc.kind === "hook"
    ? `@tuja/ui/hooks/${doc.name}`
    : `@tuja/ui/components/${doc.name}`;
}

function importLineOf(doc: PropsDoc): string {
  return `import { ${doc.component} } from "${importPathOf(doc)}";`;
}

/** `@tuja/ui/components/card`, or `@tuja/ui/components/{card,card-header}` for a family. */
function importPathsOf(docs: readonly PropsDoc[]): string {
  const lead = docs.at(0);
  if (lead === undefined) return "";
  if (docs.length === 1) return importPathOf(lead);
  const prefix = importPathOf(lead).slice(0, -lead.name.length);
  return `${prefix}{${docs.map((doc) => doc.name).join(",")}}`;
}

function propLine(prop: PropDoc): string {
  const signature = `${prop.name}${prop.required ? "" : "?"}: ${prop.type}${
    prop.defaultValue === undefined ? "" : ` = ${prop.defaultValue}`
  }`;
  const summary = summaryOf(prop.description.en);
  const lines = [
    `- ${code(signature)}${summary === "" ? "" : ` — ${summary}`}`,
  ];
  for (const shape of prop.shapes ?? []) lines.push(`  - ${code(shape)}`);
  return lines.join("\n");
}

function renderDoc(doc: PropsDoc, withHeading: boolean): string {
  const props = doc.props.filter(
    (prop) => prop.name !== "css" && prop.deprecated === undefined,
  );
  const noun = doc.kind === "hook" ? "Options" : "Props";
  const inherited =
    doc.extendsHtml === undefined
      ? ""
      : `, and every attribute of ${code(`<${doc.extendsHtml}>`)}`;
  const body =
    props.length === 0
      ? `${noun}: \`css\`${inherited}.`
      : `${noun} (also \`css\`${inherited}):\n\n${props.map(propLine).join("\n")}`;
  return withHeading ? `### ${doc.component}\n\n${body}` : body;
}

interface ResolvedEntry {
  entry: CatalogueEntry;
  docs: PropsDoc[];
}

function renderEntryDetail(
  { entry, docs }: ResolvedEntry,
  examples: ReadonlyMap<string, string>,
  usedExamples: Set<string>,
): string {
  const parts = [
    `## ${docs.map((doc) => doc.component).join(", ")}`,
    "```tsx\n" + docs.map(importLineOf).join("\n") + "\n```",
    entry.when,
  ];
  if (entry.note !== undefined) parts.push(entry.note);
  parts.push(...docs.map((doc) => renderDoc(doc, docs.length > 1)));
  for (const doc of docs) {
    const example = examples.get(doc.component);
    if (example === undefined) continue;
    usedExamples.add(doc.component);
    parts.push("Example:", "```tsx\n" + example + "\n```");
  }
  return parts.join("\n\n");
}

function primitiveLine(
  primitive: PrimitiveEntry,
  members: ReadonlyMap<string, readonly string[]>,
): string {
  const keys = members.get(primitive.name) ?? [];
  const name =
    keys.length === 0
      ? primitive.name
      : `${primitive.name}.{${keys.join(",")}}`;
  return `- \`${name}\` from \`@tuja/ui/primitives/${primitive.file}.stylex\`: ${primitive.when}`;
}

function renderPrimitivesDetail(
  primitives: readonly PrimitiveEntry[],
  members: ReadonlyMap<string, readonly string[]>,
): string {
  const imports = [
    ...new Set(primitives.map((primitive) => primitive.file)),
  ].map(
    (file) =>
      `import { ${primitives
        .filter((primitive) => primitive.file === file)
        .map((primitive) => primitive.name)
        .join(", ")} } from "@tuja/ui/primitives/${file}.stylex";`,
  );
  return [
    "## Layout primitives",
    "StyleX style objects for the space between components. Compose them in `css`: `<div css={stack.group}>`, `<div css={[row.inline, styles.mine]}>`.",
    "```tsx\n" + imports.join("\n") + "\n```",
    primitives.map((primitive) => primitiveLine(primitive, members)).join("\n"),
  ].join("\n\n");
}

const INDEX_INTRO = [
  "# Components",
  "The catalogue of `@tuja/ui`. Each line names a component, where it imports from and when to reach for it, in the order a screen is built. Each group ends with its detail file: every prop and an example.",
  [
    '- Import each component from its own path, `import { ListRow } from "@tuja/ui/components/list-row";`. A path in braces, `components/{card,card-header}`, is one path per name.',
    "- Every component takes `css`, StyleX styles composed last, and none takes `className` or `style`.",
    '- Icons are Phosphor: `import { PlusIcon } from "@phosphor-icons/react/dist/ssr/Plus";`, passed as `icon={<PlusIcon weight="bold" />}`. A `TabView` item takes the component itself, `icon: PlusIcon`.',
    '- The apps translate every string a visitor reads, `t({ en: "Save", zh: "保存" })` (the `i18n-patterns` skill); the examples use plain strings.',
    "- In a Next app, the `linkComponent` and `linkStatus` of `TabView` and `NavigationSplitView` take `Link` and `LinkStatus` from `@tuja/next-links/link`.",
  ].join("\n"),
].join("\n\n");

function indexLine({ entry, docs }: ResolvedEntry): string {
  const names = docs.map((doc) => `\`${doc.component}\``).join(", ");
  return `- ${names} from \`${importPathsOf(docs)}\`: ${entry.when}`;
}

/** The catalogue page and one detail page per group, from the props documents. */
export function renderAgentIndex(input: AgentIndexInput): AgentIndex {
  const listed = new Set(
    input.catalogue.flatMap((group) =>
      group.entries.flatMap((entry) => entry.names),
    ),
  );
  const unknown = [...listed].filter((name) => !input.docs.has(name));
  const unlisted = [...input.docs.keys()].filter((name) => !listed.has(name));

  const groups: CatalogueGroup[] = [...input.catalogue];
  if (unlisted.length > 0) {
    groups.push({
      slug: OTHER_SLUG,
      title: "Other",
      entries: unlisted.map((name) => ({
        names: [name],
        when: "Not in a group yet: read its props.",
      })),
    });
  }

  const files = new Map<string, string>();
  const usedExamples = new Set<string>();
  const indexSections = [GENERATED_NOTICE, INDEX_INTRO];

  for (const group of groups) {
    const resolved = group.entries
      .map((entry) => ({
        entry,
        docs: entry.names.flatMap((name) => {
          const doc = input.docs.get(name);
          return doc ? [doc] : [];
        }),
      }))
      .filter(({ docs }) => docs.length > 0);
    const detailPath = `components/${group.slug}.md`;

    const indexLines = [
      ...resolved.map(indexLine),
      ...(group.primitives ?? []).map((primitive) =>
        primitiveLine(primitive, input.primitiveMembers),
      ),
    ];
    indexSections.push(
      `## ${group.title}`,
      indexLines.join("\n"),
      `Props and examples: [${detailPath}](${detailPath})`,
    );

    const detailSections = [
      GENERATED_NOTICE,
      `# ${group.title}`,
      "From [the component index](../components.md). A prop with `?` is optional, and `= x` is its default. An indented line is the shape of a value the prop takes. In the examples, `children`, `transactions`, the icons and the handlers stand for the screen's own content, data and state.",
      ...resolved.map((item) =>
        renderEntryDetail(item, input.examples, usedExamples),
      ),
    ];
    if (group.primitives !== undefined) {
      detailSections.push(
        renderPrimitivesDetail(group.primitives, input.primitiveMembers),
      );
    }
    files.set(detailPath, detailSections.join("\n\n") + "\n");
  }

  files.set("components.md", indexSections.join("\n\n") + "\n");

  return {
    files,
    unlisted,
    unknown,
    unusedExamples: [...input.examples.keys()].filter(
      (name) => !usedExamples.has(name),
    ),
  };
}
