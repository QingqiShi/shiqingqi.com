/**
 * The attribute of the element inside a segmented control's track that
 * draws the indicator: the effect draws in its place, with its colours, its
 * corners and its shadow.
 *
 * @internal
 */
export const LIQUID_INDICATOR = "data-liquid-indicator";

/**
 * The attribute of each segment inside a segmented control's track, such as
 * a radio or a link: the liquid rests in a pill as long as the segment.
 *
 * @internal
 */
export const LIQUID_SEGMENT = "data-liquid-segment";

/**
 * The attribute of the bar inside a Sheet's grabber: the liquid swells out
 * of the bar on the card while the card moves or a finger holds it, and
 * sets into the bar again. The effect reads the bar's size and colour, and
 * the card's colour under it.
 *
 * @internal
 */
export const LIQUID_GRABBER = "data-liquid-grabber";
