import fs from "fs";
import path from "path";
import { apiRoutes } from "./api-routes.js";

/**
 * Replace the `/api/tmdb` route directory with one route per api route.
 * @param {string} projectRoot - Root of the app the output belongs to
 */
export function generateApiRoutes(projectRoot) {
  // Clean up existing API route files
  const apiDir = path.join(projectRoot, "src", "app", "api", "tmdb");
  if (fs.existsSync(apiDir)) {
    // Only remove files that match our generation pattern
    const files = fs.readdirSync(apiDir).sort();
    files.forEach((file) => {
      const filePath = path.join(apiDir, file);
      if (fs.statSync(filePath).isDirectory()) {
        const routeFile = path.join(filePath, "route.ts");
        if (fs.existsSync(routeFile)) {
          const content = fs.readFileSync(routeFile, "utf8");
          if (content.includes("apiRouteWrapper")) {
            fs.rmSync(filePath, { recursive: true });
            console.log(`🗑️  Removed existing route: ${file}`);
          }
        }
      }
    });
  }

  // Generate new API routes
  apiRoutes.forEach(({ functionName, routePath }) => {
    const routeDir = path.join(apiDir, routePath);
    fs.mkdirSync(routeDir, { recursive: true });

    const routeContent = `/**
 * Auto-generated API route for TMDB ${functionName}
 *
 * This file is auto-generated by packages/tmdb-codegen/src/generator.js
 * Do not edit manually - changes will be overwritten.
 */

import { ${functionName} } from "#src/_generated/tmdb-server-functions.ts";
import { apiRouteWrapper } from "#src/utils/api-route-wrapper.ts";

export const GET = apiRouteWrapper(${functionName});
`;

    const routeFile = path.join(routeDir, "route.ts");
    fs.writeFileSync(routeFile, routeContent, "utf8");
    console.log(`✅ Generated API route: /api/tmdb/${routePath}`);
  });
}
