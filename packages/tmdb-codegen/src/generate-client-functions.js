import fs from "fs";
import path from "path";
import { apiRoutes } from "./api-routes.js";

/**
 * Write one client function per api route into `_generated`. Each has the
 * signature of its server function and reaches it through the route.
 * @param {string} projectRoot - Root of the app the output belongs to
 */
export function generateClientFunctions(projectRoot) {
  const functions = apiRoutes
    .slice()
    .sort((a, b) => a.functionName.localeCompare(b.functionName))
    .map(
      ({ functionName, routePath }) =>
        `export const ${functionName}: typeof server.${functionName} = (params) =>
  apiRequestWrapper<typeof server.${functionName}>("/api/tmdb/${routePath}", params);`,
    );

  const fileContent = `import { apiRequestWrapper } from "../utils/api-request-wrapper";
import type * as server from "./tmdb-server-functions";

/**
 * Client functions for TMDB APIs - each one has the signature of the server
 * function with the same name, and calls it through its API route.
 *
 * This file is auto-generated by packages/tmdb-codegen/src/generator.js
 * Do not edit manually - changes will be overwritten.
 */

${functions.join("\n\n")}
`;

  const outputPath = path.join(
    projectRoot,
    "src",
    "_generated",
    "tmdb-client-functions.ts",
  );
  fs.writeFileSync(outputPath, fileContent, "utf8");
  console.log("✅ Generated tmdb-client-functions.ts");
}
